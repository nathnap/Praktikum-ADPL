    private void siapkanForm() {
        tblRiwayat.setModel(modelTable);
        cmbLayanan.removeAllItems();
        for (LayananPengiriman layananPengiriman : daftarLayanan) {
            cmbLayanan.addItem(layananPengiriman.getNama());
        }
        aturAsuransi();
        tampilakanRiwayat();
        
    }
    
    private void aturAsuransi() {
        int indeks = cmbLayanan.getSelectedIndex();
        if (indeks < 0) {
            return;
        }
        boolean bisaAsuransi = daftarLayanan.get(indeks) instanceof BisaDiasuransikan;
        chkAsuransi.setEnabled(bisaAsuransi);
        if (!bisaAsuransi) {
            chkAsuransi.setSelected(false);
        }
    }
    
    private void simpan() {
        try {
            double berat = Double.parseDouble(txtBerat.getText().trim().replace(',', '.'));
            LayananPengiriman layanan = daftarLayanan.get(cmbLayanan.getSelectedIndex());
            
            Pengiriman hasil = service.kirim(
                    txtPenerima.getText(), berat, layanan, chkAsuransi.isSelected()
                    );
            
            lblTotal.setText("Total Ongkir: " + rupiah(hasil.getTotalOngkir()));
            tampilakanRiwayat();
        } catch (NumberFormatException e) {
            JOptionPane.showConfirmDialog(
                    this, 
                    "Berat harus berupa angka, contoh: 2 atau 1,5.",
                    "Input Tidak Valid", JOptionPane.WARNING_MESSAGE
            );
        } catch (IllegalArgumentException e) {
            JOptionPane.showConfirmDialog(
                    this, 
                    e.getMessage(),
                    "Input Tidak Valid", JOptionPane.WARNING_MESSAGE
            );
        }
    }
    
    private String angka(double nilai){
        return NumberFormat.getNumberInstance(INDONESIA).format(nilai);
    }
    
    private String rupiah(double nilai) {
        NumberFormat format = NumberFormat.getNumberInstance(INDONESIA);
        format.setMaximumFractionDigits(0);
        return "Rp." + format.format(nilai);
    }
        
    private void tampilakanRiwayat() {
        modelTable.setRowCount(0);
        int no = 1;
        for (Pengiriman p : service.ambilRiwayat()) {
            modelTable.addRow(new Object[]{
                no++,
                p.getPenerima(),
                p.getNamaLayanan(),
                angka(p.getBerat()),
                p.isPakaiAsuransi() ? "Ya" : "Tidak",
                rupiah(p.getTotalOngkir())
            });
            
        }
    }
    
    private void bersihkan() {
        txtPenerima.setText("");
        txtBerat.setText("");
        cmbLayanan.setSelectedIndex(0);
        chkAsuransi.setSelected(false);
        lblTotal.setText("Total Ongkir: Rp0");
    }
    
